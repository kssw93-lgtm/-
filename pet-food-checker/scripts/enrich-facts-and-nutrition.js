function enrich() {
  const data = JSON.parse(fs.readFileSync(FOODS_PATH, "utf8"));

  const updated = data.map((item) => {
    const dog = { ...item.dog };
    const cat = { ...item.cat };

    dog.benefits = dog.safety === "안전" ? BENEFITS[item.id] || null : null;
    cat.benefits =
      cat.safety === "안전"
        ? CAT_BENEFIT_OVERRIDES[item.id] || BENEFITS[item.id] || null
        : null;

    if (DOSE_BY_SIZE[item.id]) {
      dog.dose_by_size = DOSE_BY_SIZE[item.id];
    }

    return { ...item, dog, cat };
  });

  const withNewItems = [...updated, ...NEW_ITEMS];

  fs.writeFileSync(FOODS_PATH, JSON.stringify(withNewItems, null, 2) + "\n");
  console.log(
    `enriched ${updated.length} existing items, added ${NEW_ITEMS.length} new items -> total ${withNewItems.length}`
  );
}

enrich();
